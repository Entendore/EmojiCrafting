def main():
    g=Game();run=True
    while run:
        dt2=clock.tick(60)/1000.0
        for ev in pygame.event.get():
            if ev.type==pygame.QUIT:run=False
            elif ev.type==pygame.MOUSEBUTTONDOWN:
                if ev.button==1:g.onmd(ev.pos)
                elif ev.button==4:g.onscr(1)
                elif ev.button==5:g.onscr(-1)
            elif ev.type==pygame.MOUSEBUTTONUP:
                if ev.button==1:g.onmu(ev.pos)
            elif ev.type==pygame.MOUSEMOTION:g.onmm(ev.pos)
            elif ev.type==pygame.KEYDOWN:
                if ev.key==pygame.K_ESCAPE:run=False
                elif ev.key==pygame.K_h:g.sh=not g.sh
                elif ev.key==pygame.K_c:g.clr()
                elif ev.key==pygame.K_r:g.load(g.li if g.mode=="campaign" else 0)
                elif ev.key==pygame.K_TAB:
                    g.mode = "procedural" if g.mode == "campaign" else "campaign"
                    g.load(0)
                elif ev.key==pygame.K_n and g.mode=="procedural":
                    g.new_proc()
                elif ev.key in (pygame.K_1,pygame.K_2,pygame.K_3,pygame.K_4,pygame.K_5):
                    if g.mode == "procedural":
                        g.proc_difficulty = ev.key - pygame.K_0
                        g.new_proc()
        g.update(dt2);g.draw(screen);pygame.display.flip()
    pygame.quit();sys.exit()

if __name__=="__main__":main()