class Particle:
    __slots__=['x','y','vx','vy','life','ml','sz','c']
    def __init__(s,x,y,c):
        s.x,s.y=x,y; a=random.uniform(0,6.283); sp=random.uniform(2,7)
        s.vx,s.vy=math.cos(a)*sp,math.sin(a)*sp
        s.life=s.ml=random.uniform(.4,1.2); s.sz=random.randint(3,8); s.c=c
    def up(s,dt): s.x+=s.vx;s.y+=s.vy;s.vy+=3*dt;s.life-=dt
    def dr(s,sf):
        a=max(0,s.life/s.ml);sz=max(1,int(s.sz*a))
        pygame.draw.circle(sf,s.c,(int(s.x),int(s.y)),sz)

