def draw_rrect(s, c, r, rad=12, bw=0, bc=None):
    x,y,w,h = r
    pygame.draw.rect(s,c,(x+rad,y,w-2*rad,h))
    pygame.draw.rect(s,c,(x,y+rad,w,h-2*rad))
    for cx,cy in [(x+rad,y+rad),(x+w-rad,y+rad),(x+rad,y+h-rad),(x+w-rad,y+h-rad)]:
        pygame.draw.circle(s,c,(cx,cy),rad)
    if bw>0 and bc: pygame.draw.rect(s,bc,(x,y,w,h),bw,border_radius=rad)

