# Deduplicate and filter no-ops
CLEAN_RECIPES = []
_seen = set()
for inp, out in RAW:
    if inp in _seen: continue
    if Counter(out) == Counter(inp): continue
    _seen.add(inp)
    CLEAN_RECIPES.append((inp, out))

def find_recipe(input_emojis):
    key = tuple(sorted(input_emojis))
    for ri, ro in CLEAN_RECIPES:
        if key == ri: return ro
    return None

# ══════════════════════════════════════════════════════
# PROCEDURAL LEVEL GENERATOR
# ══════════════════════════════════════════════════════
BASE_EMOJIS = [EARTH, WATER, FIRE, AIR, SUN, MOON, STAR, SEED, ROCK, CLOUD]

# Build reverse lookup: output -> list of input tuples that produce it
_rev = {}
for ri, ro in CLEAN_RECIPES:
    for o in ro:
        _rev.setdefault(o, []).append(ri)

def _is_base(e):
    return e in BASE_EMOJIS

# Module-level cache for BFS decomposition
_decompose_cache = {}

def _bfs_decompose(target, max_depth=8, max_materials=15):
    """BFS from target backwards to find base materials needed.
    Returns (materials_list, steps, hint_text) or None if unsolvable."""
    _decompose_cache.clear()
    cache = _decompose_cache
    def decompose(item, depth):
        if depth > max_depth: return None
        if _is_base(item): return ([item], 0, item)
        if item in cache: return cache[item]
        if item not in _rev: return None  # uncraftable
        best = None
        for ri in _rev[item]:
            total_mats = []
            total_steps = 1
            chain_parts = []
            ok = True
            for inp in ri:
                result = decompose(inp, depth + 1)
                if result is None: ok = False; break
                mats, steps, chain = result
                total_mats.extend(mats)
                total_steps += steps
                chain_parts.append(chain)
            if not ok: continue
            if len(total_mats) > max_materials: continue
            if best is None or total_steps < best[1] or (total_steps == best[1] and len(total_mats) < len(best[0])):
                inp_names = []
                seen_names = set()
                for c in chain_parts:
                    if c not in seen_names:
                        inp_names.append(c)
                        seen_names.add(c)
                hint = " -> ".join(inp_names) + f" -> {item}"
                best = (total_mats, total_steps, hint)
        cache[item] = best
        return best
    return decompose(target, 0)

def _get_craftable_targets():
    """Get all non-base emojis that are recipe outputs and decomposable."""
    targets = []
    for ri, ro in CLEAN_RECIPES:
        for o in ro:
            if not _is_base(o) and o not in targets:
                targets.append(o)
    return targets

