def generate_procedural_level(difficulty=1):
    """Generate a random solvable puzzle.
    difficulty: 1=Easy(1-2 steps), 2=Medium(2-4), 3=Hard(3-6), 4=Expert(4-8), 5=Master(5-10)
    Returns dict like a LEVELS entry, or None."""
    depth_ranges = {1:(1,2), 2:(2,4), 3:(3,6), 4:(4,8), 5:(5,10)}
    mat_ranges = {1:(3,5), 2:(4,7), 3:(6,10), 4:(8,13), 5:(10,16)}
    min_d, max_d = depth_ranges.get(difficulty, (2,4))
    min_m, max_m = mat_ranges.get(difficulty, (4,8))

    targets = _get_craftable_targets()
    random.shuffle(targets)

    # Filter targets by known recipe depth
    good_targets = []
    for t in targets:
        result = _bfs_decompose(t, max_depth=max_d, max_materials=max_m)
        if result and min_d <= result[1] <= max_d and min_m <= len(result[0]) <= max_m:
            good_targets.append((t, result))
        if len(good_targets) >= 50:
            break

    if not good_targets:
        # Fallback: try easier targets
        for t in targets[:100]:
            result = _bfs_decompose(t, max_depth=max_d+2, max_materials=max_m+5)
            if result and result[1] >= 1:
                good_targets.append((t, result))
            if len(good_targets) >= 20:
                break

    if not good_targets:
        return None

    target, (materials, steps, hint_chain) = random.choice(good_targets)

    # Add 1-3 random decoy materials (base elements not needed)
    decoys = []
    needed_set = set(materials)
    available_decoys = [e for e in BASE_EMOJIS if e not in needed_set]
    if available_decoys:
        num_decoys = min(random.randint(1, 3), len(available_decoys))
        decoys = random.sample(available_decoys, num_decoys)

    all_mats = materials + decoys
    random.shuffle(all_mats)

    diff_names = {1:"Easy", 2:"Medium", 3:"Hard", 4:"Expert", 5:"Master"}
    return {
        "name": f"Procedural ({diff_names.get(difficulty,'?')})",
        "desc": f"Craft the target in {steps} step{'s' if steps!=1 else ''}!",
        "materials": all_mats,
        "objective": target,
        "obj_name": get_name(target),
        "hint": f"Chain: {hint_chain}",
        "proc_steps": steps,
    }

